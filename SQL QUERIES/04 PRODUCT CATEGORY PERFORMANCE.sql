--Calculate the total sales and total profit for each product category.
SELECT CATEGORY,
SUM(SALES) AS TOTAL_SALES,
SUM(PROFIT) AS TOTAL_PROFIT
FROM ORDERS
GROUP BY CATEGORY



--OBSERVATION: TECHNOLOGY IS THE BEST PERFORMING PRODUCT CATEGORY IN TERMS OF BOTH SALES 
--AND PROFIT, WHILE FURNITURE GENERATES THE LOWEST PROFIT DESPITE HAVING HIGHER SALES THAN OFFICE SUPPLIES