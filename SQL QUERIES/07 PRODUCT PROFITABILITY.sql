--Identify the Top 5 most profitable product sub-categories.
SELECT TOP 5 
SUB_CATEGORY,
SUM(PROFIT) AS TOTAL_PROFIT
FROM ORDERS
GROUP BY SUB_CATEGORY
ORDER BY TOTAL_PROFIT DESC


--OBSERVATION: COPIERS GENERATED THE HIGHEST AMONG THE FIVE SUB CATEGORIES 
--WHILE BINDERS RECORDED THE LOWEST. COPIERS IS THE MOST PROFITABLE IN THE PRODUCT SUB CATEGORY.
