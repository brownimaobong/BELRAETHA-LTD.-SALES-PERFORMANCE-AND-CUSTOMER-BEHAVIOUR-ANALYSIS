--Determine which product categories generated more than $10,000 in total profit.
SELECT CATEGORY,
SUM(PROFIT) AS TOTAL_PROFIT
FROM ORDERS
GROUP BY CATEGORY
HAVING SUM(PROFIT) >10000


--OBSERVATION: ALL THREE PRODUCTS CATEGORIES GENERATED MORE THAN $10000 IN TOTAL PROFIT.
--TECHNOLOGY RECORDED THE HIGHEST PROFIT WHILE FURNITURE RECORDED THE LOWEST